# Arithmetic Operators

a = 20
b = 6

print(a + b)
print(a - b)
print(a * b)
print(a / b)
print(a // b)
print(a % b)
print(a ** 2)

# Comparison Operators

x = 10
y = 20

print(x == y)
print(x != y)
print(x > y)
print(x < y)
print(x >= y)
print(x <= y)

# Logical Operators

age = 25
has_experience = True

print(age >= 18 and has_experience)
print(age >= 18 or has_experience)
print(not has_experience)
