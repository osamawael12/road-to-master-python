# if
age = 25

if age >= 18:
    print("Adult")


# if / else
score = 75

if score >= 60:
    print("Passed")
else:
    print("Failed")


# if / elif / else
score = 85

if score >= 90:
    grade = "A"
elif score >= 80:
    grade = "B"
elif score >= 70:
    grade = "C"
else:
    grade = "F"

print("Grade:", grade)


